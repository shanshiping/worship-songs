function normalizeLabel(name: string): string {
  return name.trim().replace(/\s+/g, '')
}

export function isValidSongName(name: string): boolean {
  if (!name || name.trim() === '') {
    return false
  }

  const trimmedName = name.trim()
  const compactName = normalizeLabel(trimmedName)

  if (trimmedName.length < 2 || trimmedName.length > 50) {
    return false
  }

  if (EXACT_NON_SONG_NAMES.has(compactName) || EXACT_NON_SONG_NAMES.has(trimmedName)) {
    return false
  }

  for (const keyword of excludeKeywords) {
    if (trimmedName === keyword || compactName === keyword) {
      return false
    }
    if (keyword.length >= 3 && trimmedName.includes(keyword)) {
      return false
    }
  }

  for (const pattern of excludePatterns) {
    if (pattern.test(trimmedName) || pattern.test(compactName)) {
      return false
    }
  }

  if (/^\d+[\.\、\-\s]/.test(trimmedName)) {
    return false
  }

  if (/[；;：:，,]/.test(trimmedName)) {
    return false
  }

  if (/[【】\[\]{}]/.test(trimmedName)) {
    return false
  }

  if (trimmedName === '？' || trimmedName === '?' || trimmedName === '未知') {
    return false
  }

  return true
}

export function cleanSongName(name: string): string {
  return name
    .trim()
    .replace(/^另外[；;：:\s]*/u, '')
    .replace(/\s+/g, ' ')
    .replace(/^[\d\.\、\-\s]+/, '')
    .replace(/[\n\r]+/g, ' ')
    .replace(/（.*?）/g, '')
    .replace(/\(.*?\)/g, '')
    .replace(/^[；;：:，,\s]+/g, '')
    .replace(/[；;：:，,\s]+$/g, '')
    .trim()
}

export function parseSongNames(songStr: string): string[] {
  if (!songStr || songStr.trim() === '' || songStr === '无聚会') {
    return []
  }

  const songs = songStr.split(/[+\n\/、；;]/).map((s) => s.trim())

  return songs
    .map((s) => cleanSongName(s))
    .filter((s) => isValidSongName(s))
}
